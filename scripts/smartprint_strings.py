#!/usr/bin/env python3
"""Generates src/slic3r/GUI/SmartPrintStrings.cpp from the Smart Print page's English strings
(resources/web/dialog/SmartPrint/strings.js), so every page string goes through the .po catalogs.
Run it after editing strings.js."""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / "resources/web/dialog/SmartPrint/strings.js").read_text(encoding="utf-8")
body = source[source.index("const SP_STRINGS = {"):source.index("};")]
entries = re.findall(r'^\s*([a-z0-9_]+):\s*("(?:[^"\\]|\\.)*")\s*,?\s*$', body, re.M)

lines = []
for key, literal in entries:
    text = json.loads(literal)
    cpp = text.replace("\\", "\\\\").replace('"', '\\"')
    if "%" in text:
        # Placeholders are filled by the page's T(), not printf/boost::format.
        lines.append("        // xgettext:no-c-format, no-boost-format")
    if "%s" in text:
        lines.append("        // TRN Smart Print assistant. Each %s is filled in by the page; keep them.")
    lines.append(f'        {{"{key}", _u8L_CONTEXT("{cpp}", "Smart Print")}},')

out = f"""// Generated by scripts/smartprint_strings.py from resources/web/dialog/SmartPrint/strings.js.
// Do not edit by hand; edit strings.js and run the script.
#include "SmartPrintStrings.hpp"

#include "I18N.hpp"

namespace Slic3r {{ namespace GUI {{

nlohmann::json smart_print_ui_strings()
{{
    return {{
{chr(10).join(lines)}
    }};
}}

}}}} // namespace Slic3r::GUI
"""
(root / "src/slic3r/GUI/SmartPrintStrings.cpp").write_text(out, encoding="utf-8")
print(f"{len(entries)} strings")
